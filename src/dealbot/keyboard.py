"""한/영 전환을 잊고 친 영문 값 되돌리기 (예: 쿠팡 서브 ID 'hot' → 'ㅗㅐㅅ').

두벌식 자판 위치 그대로 영문 키로 바꾼다. 완성형 글자(핫)는 자모로 풀어서 바꾼다.
"""
from __future__ import annotations

# 두벌식 자모 → 같은 자리의 영문 키 (쌍자음·겹모음은 Shift / 두 키)
_JAMO = {
    "ㅂ": "q", "ㅈ": "w", "ㄷ": "e", "ㄱ": "r", "ㅅ": "t", "ㅛ": "y", "ㅕ": "u", "ㅑ": "i", "ㅐ": "o", "ㅔ": "p",
    "ㅁ": "a", "ㄴ": "s", "ㅇ": "d", "ㄹ": "f", "ㅎ": "g", "ㅗ": "h", "ㅓ": "j", "ㅏ": "k", "ㅣ": "l",
    "ㅋ": "z", "ㅌ": "x", "ㅊ": "c", "ㅍ": "v", "ㅠ": "b", "ㅜ": "n", "ㅡ": "m",
    "ㅃ": "Q", "ㅉ": "W", "ㄸ": "E", "ㄲ": "R", "ㅆ": "T", "ㅒ": "O", "ㅖ": "P",
    "ㅘ": "hk", "ㅙ": "ho", "ㅚ": "hl", "ㅝ": "nj", "ㅞ": "np", "ㅟ": "nl", "ㅢ": "ml",
    "ㄳ": "rt", "ㄵ": "sw", "ㄶ": "sg", "ㄺ": "fr", "ㄻ": "fa", "ㄼ": "fq", "ㄽ": "ft", "ㄾ": "fx", "ㄿ": "fv",
    "ㅀ": "fg", "ㅄ": "qt",
}
_L = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
_V = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
_T = ["", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ", "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ",
      "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"]


def _jamo(ch: str) -> str:
    code = ord(ch) - 0xAC00
    if 0 <= code < 11172:  # 완성형 한글 → 초성·중성·종성
        return _L[code // 588] + _V[(code % 588) // 28] + _T[code % 28]
    return ch


def from_korean_keyboard(text: str) -> str:
    """한글 자판 상태로 친 글자를 영문 키로. 한글이 없으면 그대로."""
    return "".join(_JAMO.get(j, j) for ch in text for j in _jamo(ch))


def is_ascii(text: str | None) -> bool:
    return text is None or text.isascii()
